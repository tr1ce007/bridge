// Generates supabase/seed.sql from src/content/*.json so the database and the
// bundled content cannot drift apart.   Run: node scripts/build-seed.mjs
import { readFileSync, writeFileSync } from "node:fs";

const read = (f) => JSON.parse(readFileSync(new URL(`../src/content/${f}`, import.meta.url), "utf8"));
const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replaceAll("'", "''")}'`);
const j = (v) => `${q(JSON.stringify(v))}::jsonb`;

const out = ["-- GENERATED by scripts/build-seed.mjs from src/content/*.json. Do not edit by hand.", ""];

out.push("insert into public.stories (id, kind, status, lang, source_url, source_name, attribution, published_at, content, tags, incomplete) values");
out.push(
  read("stories.json")
    .map((s) => {
      const { id, kind, lang, sourceUrl, sourceName, attribution, publishedAt, tags, incomplete, status, ...content } = s;
      return `  (${q(id)}, ${q(kind)}, ${q(status ?? "approved")}, ${q(lang)}, ${q(sourceUrl)}, ${q(sourceName)}, ${j(attribution)}, ${q(publishedAt)}, ${j(content)}, ${j(tags)}, ${j(incomplete ?? [])})`;
    })
    .join(",\n") + "\non conflict (id) do nothing;",
);
out.push("");

out.push("insert into public.experiments (id, direction, difficulty, content) values");
out.push(
  read("experiments.json")
    .map(({ id, direction, difficulty, ...content }) => `  (${q(id)}, ${q(direction)}, ${q(difficulty)}, ${j(content)})`)
    .join(",\n") + "\non conflict (id) do nothing;",
);
out.push("");

out.push("insert into public.opportunities (id, name, kind, levels, description, eligibility, url, deadline, verified_at, status) values");
out.push(
  read("opportunities.json")
    .map(
      (o) =>
        `  (${q(o.id)}, ${q(o.name)}, ${q(o.kind)}, ${q(`{${o.levels.join(",")}}`)}::text[], ${j(o.description)}, ${j(o.eligibility)}, ${q(o.url)}, ${q(o.deadline)}::date, ${q(o.verifiedAt)}::date, ${q(o.status)})`,
    )
    .join(",\n") + "\non conflict (id) do nothing;",
);
out.push("");

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), out.join("\n"));
console.log("supabase/seed.sql written");
